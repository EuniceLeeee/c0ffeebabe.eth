import { observeFullFamilyReleaseArtifacts } from "../src/full-family-release-artifacts.ts";

const bytes = (value: string): Uint8Array => new TextEncoder().encode(value);
const h = (value: string): Hash => hashDomain("test/full-family-release-artifact-observer/v1", value);
const stages = ["identity", "materialization", "nomination", "projection", "rehydration"] as const;

function generatedSource(name: string, value: unknown, exported: boolean): Uint8Array {
  return bytes(`/* generated by @aloha/catalog-generator; DO NOT EDIT */\n${exported ? "export " : ""}const ${name} = Object.freeze(${JSON.stringify(value)})${exported ? ";" : " as unknown as GeneratedFamilyRuntimeDescriptorV1;"}\nthrow new Error("must not execute");\n`);
}

function stageRef(familyId: string, familyDefinitionHash: Hash, stage: (typeof stages)[number] | "capability") {
  return {
    familyId,
    familyDefinitionHash,
    stage,
    capabilityId: `family.${familyId}.${stage === "capability" ? "coarse" : stage}`,
    version: "1.0.0",
    schemaHash: h(`schema:${stage}`),
    interpreterHash: h(`interpreter:${stage}`),
    ownerRef: h(`owner:${stage}`),
  };
}

interface FixtureOptions {
  readonly artifactFamilyId?: string;
  readonly duplicateFamilyCatalogEntry?: boolean;
  readonly extraReleaseFamily?: boolean;
  readonly runtimeDefinitionRootSplice?: boolean;
  readonly sourcePlanRootSplice?: boolean;
}

