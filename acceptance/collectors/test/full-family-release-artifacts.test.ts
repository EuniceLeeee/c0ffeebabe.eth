test("observer derives a complete inert full-family projection from four independent byte sources", () => {
  const value = fixture();
  const observed = observeFullFamilyReleaseArtifacts({
    releaseIntentCanonicalBytes: value.releaseBytes,
    familyCatalogSourceBytes: value.familyCatalogSourceBytes,
    runtimeCompositionSourceBytes: value.runtimeCompositionSourceBytes,
    strategyCatalogSourceBytes: value.strategyCatalogSourceBytes,
  });
  assert.equal(observed.releaseIntentRoot, value.release.releaseIntentRoot);
  assert.equal(observed.sourceContentSha256.releaseIntent, sha256Hex(value.releaseBytes));
  assert.equal(observed.families[0]?.familyId, "alpha-family");
  assert.equal(observed.families[0]?.capabilityOwnerRefs[0]?.capabilityId, "family.alpha-family.coarse");
  assert.equal(observed.globalDefinitionCatalogRoot.kind, "complete");
});

test("observer reports the global root as missing when Strategy catalog bytes are absent", () => {
  const value = fixture();
  const observed = observeFullFamilyReleaseArtifacts({
    releaseIntentCanonicalBytes: value.releaseBytes,
    familyCatalogSourceBytes: value.familyCatalogSourceBytes,
    runtimeCompositionSourceBytes: value.runtimeCompositionSourceBytes,
  });
  assert.equal(observed.globalDefinitionCatalogRoot.kind, "missing");
  if (observed.globalDefinitionCatalogRoot.kind !== "missing") assert.fail("missing Strategy catalog must not produce a global root");
  assert.equal(observed.globalDefinitionCatalogRoot.reason, "strategy-catalog-source-not-supplied");
  assert.equal(observed.globalDefinitionCatalogRoot.familyDefinitionCatalogRoot, observed.familyDefinitionCatalogRoot);
  assert.deepEqual(observed.sourceContentSha256.strategyCatalog, {
    kind: "missing",
    reason: "strategy-catalog-source-not-supplied",
  });
});

test("observer rejects dynamic generated initializers without executing them", () => {
  const value = fixture();
  assert.throws(() => observeFullFamilyReleaseArtifacts({
    releaseIntentCanonicalBytes: value.releaseBytes,
    familyCatalogSourceBytes: bytes("/* generated by @aloha/catalog-generator; DO NOT EDIT */\nexport const FAMILY_CATALOG = Object.freeze(buildCatalog());\n"),
    runtimeCompositionSourceBytes: value.runtimeCompositionSourceBytes,
  }), /literal|non-JSON/);
});

test("observer rejects release/catalog/runtime exact-set mismatch and missing release Families", () => {
  for (const value of [fixture({ artifactFamilyId: "other-family" }), fixture({ extraReleaseFamily: true })]) {
    assert.throws(() => observeFullFamilyReleaseArtifacts({
      releaseIntentCanonicalBytes: value.releaseBytes,
      familyCatalogSourceBytes: value.familyCatalogSourceBytes,
      runtimeCompositionSourceBytes: value.runtimeCompositionSourceBytes,
    }), /exact set mismatch/);
  }
});

test("observer rejects duplicate Families", () => {
  const value = fixture({ duplicateFamilyCatalogEntry: true });
  assert.throws(() => observeFullFamilyReleaseArtifacts({
    releaseIntentCanonicalBytes: value.releaseBytes,
    familyCatalogSourceBytes: value.familyCatalogSourceBytes,
    runtimeCompositionSourceBytes: value.runtimeCompositionSourceBytes,
  }), /duplicate entry/);
});

test("observer rejects global-root and source-plan-root splices", () => {
  const global = fixture({ runtimeDefinitionRootSplice: true });
  assert.throws(() => observeFullFamilyReleaseArtifacts({
    releaseIntentCanonicalBytes: global.releaseBytes,
    familyCatalogSourceBytes: global.familyCatalogSourceBytes,
    runtimeCompositionSourceBytes: global.runtimeCompositionSourceBytes,
    strategyCatalogSourceBytes: global.strategyCatalogSourceBytes,
  }), /global definition catalog root mismatch/);

  const sourcePlan = fixture({ sourcePlanRootSplice: true });
  assert.throws(() => observeFullFamilyReleaseArtifacts({
    releaseIntentCanonicalBytes: sourcePlan.releaseBytes,
    familyCatalogSourceBytes: sourcePlan.familyCatalogSourceBytes,
    runtimeCompositionSourceBytes: sourcePlan.runtimeCompositionSourceBytes,
  }), /source plan root mismatch/);
});
